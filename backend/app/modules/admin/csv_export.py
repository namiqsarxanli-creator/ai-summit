"""CSV encoding for admin exports.

Format: UTF-8 with a byte-order mark (so Excel reads Azerbaijani letters
correctly instead of guessing a legacy code page), RFC 4180 quoting
(commas, double quotes and line breaks inside a cell are quoted, quotes are
doubled), CRLF line ends.

**Formula injection.** A spreadsheet treats a cell that starts with `=`, `+`,
`-` or `@` as a formula, so user-typed text such as `=HYPERLINK(...)` would
run when an administrator opens the file. Every cell that holds text a
*person* typed (names, e-mail, profession, URLs, free-text titles) is
therefore neutralised: if its first meaningful character is one of those
four - or it starts with a tab or carriage return - a single apostrophe is put
in front. "First meaningful character" looks past anything that is invisible
in a spreadsheet cell and could be used to hide the trigger: spaces,
control characters, no-break and zero-width spaces, the BOM, and other
Unicode separators/format characters.

Columns the SERVER generates (ids, counts, point values, flags, timestamps)
are written as they are: a reversal's `-5` must stay the number -5, not the
text `'-5`. Typing the columns by kind - never guessing from the content - is
what makes that safe.

One deliberate exception, for the sponsor export's `phone` column: a value
that is strictly a phone number (a leading `+`, then only digits, spaces,
parentheses, dots and hyphens) is written as it is. A number such as
`+994 50 123 45 67` is exactly what a sponsor needs, and such a string
cannot form a function call, a link or a DDE command - it has no letters or
other symbols. Anything else in that column is neutralised like any text.
"""

from __future__ import annotations

import csv
import io
import re
import unicodedata
from collections.abc import Iterable, Sequence
from enum import StrEnum

BOM = "﻿"
_TRIGGERS = frozenset("=+-@")
_STRICT_PHONE = re.compile(r"^\+[0-9][0-9 ()\-.]*$")


class Kind(StrEnum):
    TEXT = "text"  # typed by a person: always neutralised
    PHONE = "phone"  # typed by a person; a strict phone number is left alone
    RAW = "raw"  # generated by the server: written as is


def _invisible(char: str) -> bool:
    return char.isspace() or unicodedata.category(char) in {"Cc", "Cf", "Zs", "Zl", "Zp"}


def neutralise(value: str) -> str:
    """The text with a leading apostrophe if a spreadsheet could run it."""
    if value[:1] in ("\t", "\r"):
        return "'" + value
    for char in value:
        if _invisible(char):
            continue
        return "'" + value if char in _TRIGGERS else value
    return value  # empty or entirely invisible: nothing to execute


def cell(value: object, kind: Kind) -> str:
    """One cell as the text to hand to the CSV writer."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    text = str(value)
    if kind is Kind.RAW:
        return text
    if kind is Kind.PHONE and _STRICT_PHONE.fullmatch(text):
        return text
    return neutralise(text)


def encode_rows(rows: Iterable[Sequence[object]], kinds: Sequence[Kind]) -> bytes:
    """A batch of rows as CSV bytes (no BOM, no header)."""
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\r\n")
    for row in rows:
        writer.writerow([cell(value, kind) for value, kind in zip(row, kinds, strict=True)])
    return buffer.getvalue().encode("utf-8")


def encode_header(names: Sequence[str], *, bom: bool = True) -> bytes:
    buffer = io.StringIO(newline="")
    csv.writer(buffer, lineterminator="\r\n").writerow(list(names))
    return ((BOM if bom else "") + buffer.getvalue()).encode("utf-8")
