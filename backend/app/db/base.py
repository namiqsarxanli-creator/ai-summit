"""Declarative base, naming convention, and the shared PK column.

The naming convention matters because ARCHITECTURE.md §7.14 requires
constraint violations to be dispatched by *name* ("the application
catches IntegrityError, inspects the violated constraint name, and
maps it to a domain error... never by which error the database happens
to report first"). Unnamed constraints get illegible autogenerated
names from PostgreSQL; this convention makes every constraint name
predictable and greppable in Alembic migrations, and business-critical
constraints additionally get an EXACT literal name matching
ARCHITECTURE.md §7.14's table (e.g. ``ck_staff_role_booth``) so the
constraint-error map in ``app/core/errors.py`` has something stable to
key on.
"""

from __future__ import annotations

from sqlalchemy import BigInteger, Identity, MetaData
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Shared declarative base for every ORM model in the project."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class IdentityPKMixin:
    """``id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY``.

    ARCHITECTURE.md §7's opening convention line: "surrogate id BIGINT
    GENERATED ALWAYS AS IDENTITY primary keys" — applied uniformly to
    every table. ``Identity(always=True)`` (not ``GENERATED BY
    DEFAULT``) is deliberate: it makes an ordinary INSERT that supplies
    its own id fail loudly rather than silently accepting a
    caller-chosen primary key, matching the "internal IDs are never
    exposed" posture (ARCHITECTURE.md §7) — nothing should ever have a
    legitimate reason to assign one by hand outside of an explicit,
    intentional ``OVERRIDING SYSTEM VALUE``.
    """

    id: Mapped[int] = mapped_column(BigInteger, Identity(always=True), primary_key=True)
